# --------------------------------------------------------------------------
# Derived amounts -- computed, never recalled
# --------------------------------------------------------------------------

def _rupees(value: Decimal) -> Decimal:
    """Round to whole rupees. Collections never quotes paise."""
    return value.quantize(Decimal("1"), rounding=ROUND_HALF_UP)


def compute_late_fee(outstanding_inr: Decimal) -> Decimal:
    """Late fee for a given outstanding balance.

    The threshold is strict: a balance *equal* to the threshold does not
    attract the fee. This matters -- an off-by-one here is a factual error on a
    recorded call.
    """
    if outstanding_inr > LATE_FEE_THRESHOLD_INR:
        return LATE_FEE_INR
    return Decimal("0")


def compute_monthly_interest(outstanding_inr: Decimal) -> Decimal:
    """Interest accrued over one month on the outstanding balance."""
    return _rupees(outstanding_inr * INTEREST_PCT_MONTHLY / Decimal("100"))


# --------------------------------------------------------------------------
# Accounts
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Account:
    """One delinquent credit card account.

    Stands in for the record a dialler would hand the agent at call time. In
    production this is a CRM lookup; the shape is the same.
    """

    customer_id: str
    name: str
    card_last4: str
    outstanding_inr: Decimal
    minimum_due_inr: Decimal
    due_date: date
    otp: str  # fixture only; a real deployment sends and verifies out of band
    language_hint: str = "en-IN"

    @property
    def days_past_due(self) -> int:
        return (date.today() - self.due_date).days

    @property
    def late_fee_inr(self) -> Decimal:
        return compute_late_fee(self.outstanding_inr)

    @property
    def monthly_interest_inr(self) -> Decimal:
        return compute_monthly_interest(self.outstanding_inr)

    @property
    def in_scope(self) -> bool:
        """Whether this account belongs to this agent's treatment window."""
        return DPD_MIN <= self.days_past_due <= DPD_MAX


def _days_ago(n: int) -> date:
    return date.today() - timedelta(days=n)


