"""Product facts and account data.

Everything the agent is allowed to state as fact originates here. Nothing in
this module is generated by a language model, and no figure in it is written
into prompt text as prose -- the agent reaches it through a tool call so that a
wrong number is a broken function (a test failure) rather than a hallucination.

Issuer-specific values are configuration. Point INTEREST_PCT_MONTHLY and
LATE_FEE_INR at a different product and the agent speaks the new terms with no
other change.
"""

