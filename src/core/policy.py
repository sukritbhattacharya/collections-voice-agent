# --------------------------------------------------------------------------
# Product terms -- the numbers the agent is permitted to quote
# --------------------------------------------------------------------------

#: Monthly interest on revolving credit card balance, in percent.
INTEREST_PCT_MONTHLY: Decimal = Decimal("3.5")

#: Flat late fee, in rupees, charged only above LATE_FEE_THRESHOLD_INR.
LATE_FEE_INR: Decimal = Decimal("750")

#: Outstanding balance must exceed this for the late fee to apply.
LATE_FEE_THRESHOLD_INR: Decimal = Decimal("10000")

#: How long a payment takes to reflect, quoted to customers who say they paid.
PAYMENT_REFLECT_WORKING_DAYS: int = 2

#: Delinquency window this agent is scoped to. Outside it, the call should not
#: be placed at all -- different treatment, different team, different script.
DPD_MIN: int = 1
DPD_MAX: int = 30

#: Payment modes the agent recognises when a customer says they have paid.
