# --------------------------------------------------------------------------
# Disclosure control
# --------------------------------------------------------------------------
#
# The brief says: never reveal account balance without OTP verification. It does
# not say whether the *minimum due* counts as "balance".
#
# We take the strict reading: no rupee figure tied to this account is spoken
# before verification, minimum due included. The two errors are not symmetric --
# under-disclosing makes the opening slightly awkward, over-disclosing is a data
# protection incident on a recorded line. In a real engagement this exact line
# is a question for the bank's compliance team, not a decision for the vendor.
#
# The call still works: the agent asks when the customer can clear the overdue
# amount without naming it, and offers verification the moment they ask "how
# much?".

@dataclass
class CallState:
    """Mutable per-call state. One instance per call, never shared."""

    account: Account
    otp_verified: bool = False
    otp_attempts: int = 0
    waiver_requested: bool = False
    transfer_requested: bool = False
    transfer_reason: str | None = None
    guardrail_hits: list[str] = field(default_factory=list)

    MAX_OTP_ATTEMPTS: int = 3

    def verify_otp(self, code: str) -> bool:
        """Check a code against the account. Lockout after MAX_OTP_ATTEMPTS."""
        if self.otp_attempts >= self.MAX_OTP_ATTEMPTS:
            return False
        self.otp_attempts += 1
        if code.strip() == self.account.otp:
            self.otp_verified = True
        return self.otp_verified

    @property
    def otp_locked_out(self) -> bool:
        return not self.otp_verified and self.otp_attempts >= self.MAX_OTP_ATTEMPTS


def account_context(state: CallState) -> dict:
    """What the agent is allowed to know right now.

    Amounts are present only once the customer is verified. Before that the
    agent gets the fields it needs to run the call -- who it is speaking to, how
    overdue the account is -- and an explicit instruction about what it cannot
    say, rather than a silently truncated record it might try to fill in.
    """
    acc = state.account
    base = {
        "issuer": ISSUER_NAME,
        "helpline": ISSUER_HELPLINE,
        "customer_name": acc.name,
        "card_last4": acc.card_last4,
        "days_past_due": acc.days_past_due,
        "due_date": acc.due_date.isoformat(),
        "otp_verified": state.otp_verified,
        # Product terms are public -- they are printed on the statement and in
        # the cardholder agreement, so they are not gated behind verification.
        "interest_pct_monthly": str(INTEREST_PCT_MONTHLY),
        "late_fee_inr": str(LATE_FEE_INR),
        "late_fee_threshold_inr": str(LATE_FEE_THRESHOLD_INR),
        "payment_reflect_working_days": PAYMENT_REFLECT_WORKING_DAYS,
    }

    if not state.otp_verified:
        base["amounts_locked"] = True
        base["disclosure_rule"] = (
            "Do not state any rupee amount specific to this account -- not the "
            "outstanding balance and not the minimum due. If the customer asks "
            "how much they owe, offer to verify them with a one-time password "
            "first. You may still ask when they can clear the overdue amount."
        )
        return base

    base["amounts_locked"] = False
    base["outstanding_inr"] = str(acc.outstanding_inr)
    base["minimum_due_inr"] = str(acc.minimum_due_inr)
    base["late_fee_applied_inr"] = str(acc.late_fee_inr)
    base["late_fee_applies"] = acc.late_fee_inr > 0
    base["monthly_interest_inr"] = str(acc.monthly_interest_inr)
    return base


def protected_amounts(account: Account) -> list[str]:
    """Figures that must never be spoken before verification.

    Used by the output filter to catch a leak regardless of how the model
    phrased it -- digits, comma-grouped, or with a rupee prefix.
    """
    values: list[str] = []
    for amount in (account.outstanding_inr, account.minimum_due_inr):
        n = int(amount)
        values.extend([str(n), f"{n:,}"])
    return values
