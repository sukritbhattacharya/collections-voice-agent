"""Product facts and account data.

Everything the agent is allowed to state as fact originates here. Nothing in
this module is generated by a language model, and no figure in it is written
into prompt text as prose -- the agent reaches it through a tool call so that a
wrong number is a broken function (a test failure) rather than a hallucination.

Issuer-specific values are configuration. Point INTEREST_PCT_MONTHLY and
LATE_FEE_INR at a different product and the agent speaks the new terms with no
other change.
"""

from __future__ import annotations

import os
from dataclasses import dataclass, field
from datetime import date, timedelta
from decimal import ROUND_HALF_UP, Decimal

# --------------------------------------------------------------------------
# Issuer configuration
# --------------------------------------------------------------------------

ISSUER_NAME: str = os.getenv("ISSUER_NAME", "Mumbai Bank")
ISSUER_HELPLINE: str = os.getenv("ISSUER_HELPLINE", "1800-123-4567")

# --------------------------------------------------------------------------
# Product terms -- the numbers the agent is permitted to quote
# --------------------------------------------------------------------------

#: Monthly interest on revolving credit card balance, in percent.
INTEREST_PCT_MONTHLY: Decimal = Decimal("3.5")

#: Flat late fee, in rupees, charged only above LATE_FEE_THRESHOLD_INR.
LATE_FEE_INR: Decimal = Decimal("750")

#: Outstanding balance must exceed this for the late fee to apply.
LATE_FEE_THRESHOLD_INR: Decimal = Decimal("10000")

#: How long a payment takes to reflect, quoted to customers who say they paid.
PAYMENT_REFLECT_WORKING_DAYS: int = 2

#: Delinquency window this agent is scoped to. Outside it, the call should not
#: be placed at all -- different treatment, different team, different script.
DPD_MIN: int = 1
DPD_MAX: int = 30

#: Payment modes the agent recognises when a customer says they have paid.
KNOWN_PAYMENT_MODES: tuple[str, ...] = (
    "UPI",
    "NEFT",
    "IMPS",
    "RTGS",
    "net banking",
    "debit card",
    "cheque",
    "cash at branch",
    "auto-debit",
)

#: Vocabulary hints passed to speech recognition so collections terms and
#: payment rails transcribe correctly instead of being guessed phonetically.
STT_KEYTERMS: tuple[str, ...] = (
    "NEFT", "UPI", "IMPS", "RTGS", "minimum due", "late fee",
    "outstanding", "statement", "due date", "credit card",
    "auto-debit", "net banking", "cheque", ISSUER_NAME,
)


# --------------------------------------------------------------------------
# Derived amounts -- computed, never recalled
# --------------------------------------------------------------------------

def _rupees(value: Decimal) -> Decimal:
    """Round to whole rupees. Collections never quotes paise."""
    return value.quantize(Decimal("1"), rounding=ROUND_HALF_UP)


def compute_late_fee(outstanding_inr: Decimal) -> Decimal:
    """Late fee for a given outstanding balance.

    The threshold is strict: a balance *equal* to the threshold does not
    attract the fee. This matters -- an off-by-one here is a factual error on a
    recorded call.
    """
    if outstanding_inr > LATE_FEE_THRESHOLD_INR:
        return LATE_FEE_INR
    return Decimal("0")


def compute_monthly_interest(outstanding_inr: Decimal) -> Decimal:
    """Interest accrued over one month on the outstanding balance."""
    return _rupees(outstanding_inr * INTEREST_PCT_MONTHLY / Decimal("100"))


# --------------------------------------------------------------------------
# Accounts
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Account:
    """One delinquent credit card account.

    Stands in for the record a dialler would hand the agent at call time. In
    production this is a CRM lookup; the shape is the same.
    """

    customer_id: str
    name: str
    card_last4: str
    outstanding_inr: Decimal
    minimum_due_inr: Decimal
    due_date: date
    otp: str  # fixture only; a real deployment sends and verifies out of band
    language_hint: str = "en-IN"

    @property
    def days_past_due(self) -> int:
        return (date.today() - self.due_date).days

    @property
    def late_fee_inr(self) -> Decimal:
        return compute_late_fee(self.outstanding_inr)

    @property
    def monthly_interest_inr(self) -> Decimal:
        return compute_monthly_interest(self.outstanding_inr)

    @property
    def in_scope(self) -> bool:
        """Whether this account belongs to this agent's treatment window."""
        return DPD_MIN <= self.days_past_due <= DPD_MAX


def _days_ago(n: int) -> date:
    return date.today() - timedelta(days=n)


