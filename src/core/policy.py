# --------------------------------------------------------------------------
# Disclosure control
# --------------------------------------------------------------------------
#
# The brief says: never reveal account balance without OTP verification. It does
# not say whether the *minimum due* counts as "balance".
#
# We take the strict reading: no rupee figure tied to this account is spoken
# before verification, minimum due included. The two errors are not symmetric --
# under-disclosing makes the opening slightly awkward, over-disclosing is a data
# protection incident on a recorded line. In a real engagement this exact line
# is a question for the bank's compliance team, not a decision for the vendor.
#
# The call still works: the agent asks when the customer can clear the overdue
# amount without naming it, and offers verification the moment they ask "how
# much?".

@dataclass
class CallState:
    """Mutable per-call state. One instance per call, never shared."""

    account: Account
    #: How many times the agent has re-asked because the customer said
    #: nothing. Capped, so a call to an empty room cannot run to the ceiling.
    #: See D-064.
    silence_prompts: int = 0
    #: The call ended because nobody answered, not because it concluded.
    ended_on_silence: bool = False
    #: The call was cut by the duration ceiling rather than concluded.
    #: Without this a truncated call is indistinguishable from a finished
    #: one in the record. See D-073.
    ended_on_ceiling: bool = False
    otp_verified: bool = False
    #: The code has been sent, so the agent should be waiting for the
    #: customer to read it back rather than offering again. See D-060.
    otp_sent: bool = False
    otp_attempts: int = 0
    waiver_requested: bool = False
    #: True when the waiver asked for was against a fee that is not charged on
    #: this account. `waiver_requested` alone sends a human to call back about
    #: nothing; a reviewer needs to know there is nothing to decide. See D-058.
    waiver_on_nonexistent_fee: bool = False
    transfer_requested: bool = False
    transfer_reason: str | None = None
    guardrail_hits: list[str] = field(default_factory=list)
    # Set only when the customer has been offered the chance to raise
    # something else and declined. The outcome being logged is not the same
    # event: the business of the call being finished does not mean the
    # customer is. See D-049.
    call_closed: bool = False
    #: Speech-recognition artefacts repaired before the model read them,
    #: as `raw -> repaired`. Kept separate from `guardrail_hits`: a misheard
    #: syllable is an input-quality event, not a compliance breach, and
    #: folding it in would corrupt the gate counts. See D-051.
    transcription_repairs: list[str] = field(default_factory=list)

    MAX_OTP_ATTEMPTS: int = 3

    def verify_otp(self, code: str) -> bool:
        """Check a code against the account. Lockout after MAX_OTP_ATTEMPTS."""
        if self.otp_attempts >= self.MAX_OTP_ATTEMPTS:
            return False
        self.otp_attempts += 1
        if code.strip() == self.account.otp:
            self.otp_verified = True
        return self.otp_verified

    @property
    def otp_locked_out(self) -> bool:
        return not self.otp_verified and self.otp_attempts >= self.MAX_OTP_ATTEMPTS


def account_context(state: CallState) -> dict:
    """What the agent is allowed to know right now.

    Amounts are present only once the customer is verified. Before that the
    agent gets the fields it needs to run the call -- who it is speaking to, how
    overdue the account is -- and an explicit instruction about what it cannot
    say, rather than a silently truncated record it might try to fill in.
    """
    acc = state.account
    base = {
        "issuer": ISSUER_NAME,
        "helpline": ISSUER_HELPLINE,
        "customer_name": acc.name,
        "card_last4": acc.card_last4,
        "days_past_due": acc.days_past_due,
        "due_date": acc.due_date.isoformat(),
        "otp_verified": state.otp_verified,
        # Product terms are public -- they are printed on the statement and in
        # the cardholder agreement, so they are not gated behind verification.
        "interest_pct_monthly": str(INTEREST_PCT_MONTHLY),
        "late_fee_inr": str(LATE_FEE_INR),
        "late_fee_threshold_inr": str(LATE_FEE_THRESHOLD_INR),
        "payment_reflect_working_days": PAYMENT_REFLECT_WORKING_DAYS,
        # The agent used to deflect "how do I pay?" to the helpline, because
        # it genuinely did not know. Correct behaviour, bad product: on a
        # collections call that is the single most useful sentence available,
        # and the rails are not customer-specific or sensitive. See D-050.
        "accepted_payment_modes": list(KNOWN_PAYMENT_MODES),
    }

    # Amounts are always returned. Withholding them from the model as well as
    # from the customer was the first design here, and it was wrong: the agent
    # could not record a payment commitment without first running an OTP step
    # on every call, which is a worse experience and a worse outcome rate.
    #
    # The control on disclosure is the output filter, which blocks these exact
    # figures before they reach speech while unverified. Ignorance is not the
    # safeguard; the guardrail is. See D-027.
    base["outstanding_inr"] = str(acc.outstanding_inr)
    base["minimum_due_inr"] = str(acc.minimum_due_inr)
    base["late_fee_applied_inr"] = str(acc.late_fee_inr)
    base["late_fee_applies"] = acc.late_fee_inr > 0
    base["monthly_interest_inr"] = str(acc.monthly_interest_inr)
    base["amounts_locked"] = not state.otp_verified

    if not state.otp_verified:
        base["disclosure_rule"] = (
            "THESE FIGURES ARE FOR YOUR USE ONLY. Do not say the outstanding "
            "balance or the minimum due out loud, and do not hint at them, "
            "until the customer is verified. You may use them to record a "
            "payment commitment. Do NOT offer verification unprompted -- an "
            "outbound caller asking for a code reads as a fraud attempt. "
            "Offer it only when the customer asks about something on their "
            "account, and then explain why you need it. Until then you may "
            "ask when they can clear the overdue amount without naming it, "
            "and you may state the published interest rate and late fee rule "
            "without saying whether the fee applies here."
        )
    return base


def protected_amounts(account: Account) -> list[str]:
    """Figures that must never be spoken before verification.

    Used by the output filter to catch a leak regardless of how the model
    phrased it -- digits, comma-grouped, or with a rupee prefix.
    """
    values: list[str] = []
    for amount in (account.outstanding_inr, account.minimum_due_inr):
        n = int(amount)
        values.extend([str(n), f"{n:,}"])
    return values


def account_figures(account: Account) -> list[str]:
    """Every rupee figure that legitimately belongs to this account.

    A numeric rule asking "is this the right late fee?" must not fire on the
    customer's own balance simply because the two appear in one sentence.
    """
    values: list[str] = []
    for amount in (
        account.outstanding_inr,
        account.minimum_due_inr,
        account.monthly_interest_inr,
    ):
        n = int(amount)
        values.extend([str(n), f"{n:,}"])
    return values


#: The first thing the agent says.
#:
#: Templated rather than generated, for two reasons. Generating it costs two
#: model round-trips -- a tool call for account context, then the text -- and
#: measured about 1.8 seconds of silence at the exact moment a customer
#: decides whether to stay on the line. And an opening line has nothing to
#: decide: it greets, identifies the bank, and asks for the cardholder. There
#: is no judgement in it to delegate, and a template cannot hallucinate.
#:
#: Note what it does NOT do: it does not say why we are calling. Until we know
#: we are speaking to the cardholder, mentioning an overdue payment would
#: disclose it to whoever picked up the phone.
OPENING_LINE = (
    "Hello, this is {agent_name} calling from {issuer}. "
    "Am I speaking with {customer_name}?"
)

AGENT_DISPLAY_NAME = os.getenv("AGENT_DISPLAY_NAME", "Priya")


def opening_line(account: Account) -> str:
    return OPENING_LINE.format(
        agent_name=AGENT_DISPLAY_NAME,
        issuer=ISSUER_NAME,
        customer_name=account.name,
    )
